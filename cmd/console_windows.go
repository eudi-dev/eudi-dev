//go:build windows

package cmd

import (
	"unsafe"

	"golang.org/x/sys/windows"
)

var (
	kernel32                  = windows.NewLazySystemDLL("kernel32.dll")
	procGetConsoleProcessList = kernel32.NewProc("GetConsoleProcessList")
	procFreeConsole           = kernel32.NewProc("FreeConsole")
)

// releaseOwnConsole closes the console window that Windows opened for a
// console program started from a clicked link. A console shared with a shell
// stays, so running the command by hand keeps its output. It reports whether
// the console is gone, after which only the log file receives output.
func releaseOwnConsole() bool {
	var pids [2]uint32
	n, _, _ := procGetConsoleProcessList.Call(uintptr(unsafe.Pointer(&pids[0])), uintptr(len(pids)))
	if n != 1 {
		return false
	}
	ok, _, _ := procFreeConsole.Call()
	return ok != 0
}
